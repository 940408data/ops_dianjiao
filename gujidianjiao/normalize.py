@dataclass
class NormalizedText:
    """规范化结果。cnf 与 index_map 等长，index_map[i] = cnf[i] 在 raw 中的下标。"""
    raw: str
    cnf: str
    index_map: list[int]
    punct_after: dict[int, str] = field(default_factory=dict)
    # punct_after[i] = 紧跟在 cnf[i] 之后的标点串（用于把现代本句读投影回底本）
    line_break_after: set = field(default_factory=set)
    # cnf[i] 之后在原文中存在换行（章／段边界，断句与分段的硬约束）

    def raw_slice(self, i: int, j: int) -> str:
        """取 cnf[i:j] 对应的原文字符（只取被映射的字，跳过其间标点）。"""
        if i >= j:
            return ""
        return "".join(self.raw[self.index_map[k]] for k in range(i, j))

    def raw_span(self, i: int, j: int) -> str:
        """取 cnf[i:j] 对应的连续原文片段（含其间标点），用于展示。"""
        if i >= j:
            return ""
        return self.raw[self.index_map[i]: self.index_map[j - 1] + 1]

    def context(self, i: int, j: int, width: int = 8) -> tuple[str, str]:
        left = "".join(self.raw[self.index_map[k]] for k in range(max(0, i - width), i))
        right = "".join(self.raw[self.index_map[k]] for k in range(j, min(len(self.cnf), j + width)))
        return left, right


def normalize(text: str, *, to_traditional: bool = True,
              fold_variants: bool = True, strip_punct: bool = True) -> NormalizedText:
    """把一侧文本投影到 CNF。"""
    text = unicodedata.normalize("NFC", text)
    cnf_chars: list[str] = []
    index_map: list[int] = []
    punct_after: dict[int, str] = {}

    line_break_after: set[int] = set()
    for idx, ch in enumerate(text):
        if ch in ("\n", "\r"):
            if cnf_chars:
                line_break_after.add(len(cnf_chars) - 1)
            continue
        if ch == "\t":
            continue
        if strip_punct and (ch in PUNCT_CHARS):
            if cnf_chars:
                punct_after[len(cnf_chars) - 1] = punct_after.get(len(cnf_chars) - 1, "") + ch
            continue
        c = ch
        if fold_variants:
            c = VARIANT_TO_ORTHODOX.get(c, c)
        if to_traditional:
            c = S2T.get(c, c)
            c = VARIANT_TO_ORTHODOX.get(c, c)
        cnf_chars.append(c)
        index_map.append(idx)

    return NormalizedText(raw=text, cnf="".join(cnf_chars), index_map=index_map,
                          punct_after=punct_after, line_break_after=line_break_after)


def orthographic_equal(a: str, b: str) -> bool:
    """两个原文片段在字形层是否等价（简繁/异体差异不算异文）。"""
    return normalize(a).cnf == normalize(b).cnf


def loan_note(a: str, b: str) -> str | None:
    return PHONETIC_LOANS.get(frozenset({a, b}))


def taboo_note(a: str, b: str) -> dict | None:
    return TABOO_INDEX.get(frozenset({a, b}))


def is_confusable(a: str, b: str) -> bool:
    return b in CONFUSABLE_INDEX.get(a, set())


_SENT_END = re.compile(r"[。？！；]")


def split_sentences(text: str) -> list[str]:
    out, buf = [], []
    for ch in text:
        buf.append(ch)
        if _SENT_END.match(ch):
            out.append("".join(buf))
            buf = []
    if buf:
        out.append("".join(buf))
    return out
